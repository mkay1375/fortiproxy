// Real API and real PPP session against the internal test fixture, not FortiGate.
const { chromium } = require('/app/node_modules/playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless: true, channel: 'chromium', args: ['--no-sandbox']});
  try {
    let page = await browser.newPage({viewport: {width: 1360, height: 1050}});
    await page.goto('http://127.0.0.1:8787');
    await page.locator('#status-badge[data-state="disconnected"]').waitFor();
    await page.getByLabel('Connection name', {exact: false}).fill('Local protocol test');
    await page.getByLabel('Remote gateway', {exact: true}).fill(process.env.LAB_GATEWAY);
    await page.getByLabel('Port', {exact: true}).fill('8443');
    await page.getByLabel('Username', {exact: true}).fill('test-user-otp');
    await page.getByLabel('Password', {exact: true}).fill('test-password');
    await page.getByLabel('Save password', {exact: true}).check();
    await page.getByLabel('One-time code', {exact: false}).fill('123456');
    await page.getByText('Additional settings', {exact: true}).click();
    await page.getByLabel('Ignore certificate validation', {exact: true}).check();
    await page.getByText('Additional settings', {exact: true}).click();
    await page.getByRole('button', {name: 'Test gateway', exact: true}).click();
    await page.locator('#gateway-test-message[data-result="success"]').waitFor();
    await page.getByRole('button', {name: 'Connect VPN', exact: true}).click();
    await page.locator('#status-badge[data-state="connected"]').waitFor({timeout: 25000});
    assert.equal(await page.locator('#password').inputValue(), '');
    assert.equal(await page.locator('#otp').inputValue(), '');
    await page.close();
    await new Promise(resolve => setTimeout(resolve, 1000));
    assert.equal((await (await fetch('http://127.0.0.1:8787/api/status')).json()).state, 'connected');
    page = await browser.newPage({viewport: {width: 1360, height: 1100}});
    await page.goto('http://127.0.0.1:8787');
    await page.locator('#status-badge[data-state="connected"]').waitFor();
    assert.equal(await page.locator('#save_password').isChecked(), true);
    assert.equal(await page.locator('#password').inputValue(), '');
    assert.equal(await page.locator('#password').getAttribute('placeholder'), 'Saved password');
    const profile = await (await fetch('http://127.0.0.1:8787/api/profile')).json();
    assert.equal(profile.has_saved_password, true);
    assert.equal(Object.hasOwn(profile, 'password'), false);
    assert.equal(Object.hasOwn(profile, 'otp'), false);
    await page.getByRole('button', {name: 'Disconnect VPN', exact: true}).click();
    await page.locator('#status-badge[data-state="disconnected"]').waitFor({timeout: 20000});
    await page.getByLabel('One-time code', {exact: false}).fill('123456');
    await page.getByRole('button', {name: 'Connect VPN', exact: true}).click();
    await page.locator('#status-badge[data-state="connected"]').waitFor({timeout: 25000});
    assert.equal(await page.locator('#password').inputValue(), '');
    assert.equal(await page.locator('#otp').inputValue(), '');
    await page.screenshot({path: '/artifacts/lab-connected.png', fullPage: true});
    await page.emulateMedia({colorScheme: 'dark'});
    await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
    await page.screenshot({path: '/artifacts/lab-connected-dark.png', fullPage: true});
    await page.getByRole('button', {name: 'Disconnect VPN', exact: true}).click();
    await page.locator('#status-badge[data-state="disconnected"]').waitFor({timeout: 20000});
    await page.getByLabel('Save password', {exact: true}).uncheck();
    await page.waitForFunction(() => document.querySelector('#profile-message').textContent.startsWith('Settings saved'));
    const cleared = await (await fetch('http://127.0.0.1:8787/api/profile')).json();
    assert.equal(cleared.has_saved_password, false);
    console.log('PASS: real UI save/reuse/remove base password with fresh OTP; closing page keeps VPN connected; system dark theme; real PPP connect/disconnect (no mocks).');
  } finally {
    await browser.close();
  }
})().catch(error => {console.error(error); process.exit(1);});
